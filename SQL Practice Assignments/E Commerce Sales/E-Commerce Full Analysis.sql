-- 1. How many total orders has the company received? --------------------------------------------------------------------------------------------------------------------------
 SELECT 
    COUNT(*) AS total_orders
FROM
    customers;
 
-- 2. Calculate the gross revenue generated by the company. -------------------------------------------------------------------------------------------------------------------
SELECT 
    SUM(quantity * unit_price) AS total_gross_revenue
FROM orders;

-- 3. Calculate the company's Average Order Value (AOV). -------------------------------------------------------------------------------------------------------------------------
SELECT 
    AVG(quantity * unit_price) AS avg_order_value
FROM orders;

-- 4. Find: Total orders, Total quantity sold, Total revenue for each product_category. ---------------------------------------------------------------------------------------
SELECT 
    product_category,
    COUNT(order_id) AS total_orders,
    SUM(quantity) AS total_quantity_sold,
    SUM(quantity * unit_price) AS total_gross_revenue
FROM orders
GROUP BY product_category;

-- 5. Which payment method generates the highest revenue? -------------------------------------------------------------------------------------------------------------------
SELECT 
    payment_method,
    SUM(quantity * unit_price) AS total_gross_revenue
FROM
    orders
GROUP BY payment_method
ORDER BY SUM(quantity * unit_price) DESC;

-- 6. Customer-wise Revenue - Join -----------------------------------------------------------------------------------------------------------------------------------------
SELECT 
    c.customer_id,
    c.customer_name,
    SUM(o.quantity * o.unit_price) AS total_revenue
FROM
    customers c
        LEFT JOIN
    orders o ON c.customer_id = o.customer_id
GROUP BY c.customer_id ;

-- 7. Customers Who Have Never Ordered ----------------------------------------------------------------------------------------------------------------------------------------
SELECT 
    c.customer_id, c.customer_name, o.order_id
FROM
    customers c
        LEFT JOIN
    orders o ON c.customer_id = o.customer_id
WHERE
    o.order_id IS NULL;
    
-- 8. What percentage of customers are repeat customers? -----------------------------------------------------------------------------------------------------------------------
with repeat_customers as (
SELECT customer_id, COUNT(order_id) AS order_count
    FROM orders
    GROUP BY customer_id )
SELECT 
    ROUND(
        (SUM(order_count > 1) / COUNT(*)) * 100, 
        2
    ) AS repeat_customer_percentage
FROM repeat_customers;
    

-- 9. Identify the top 3 customers by total revenue. --------------------------------------------------------------------------------------------------------------------------
SELECT 
    c.customer_id,
    c.customer_name,
    SUM(o.quantity * o.unit_price) AS total_revenue
FROM
    customers c
        JOIN
    orders o ON c.customer_id = o.customer_id
GROUP BY c.customer_id
ORDER BY SUM(o.quantity * o.unit_price) DESC
LIMIT 3;

-- 10. Find customers who have placed more than 1 orders. ----------------------------------------------------------------------------------------------------------------------
SELECT 
    customer_id, COUNT(order_id) AS order_count
FROM
    orders
GROUP BY customer_id
HAVING COUNT(order_id) > 1;

-- 11. Calculate revenue before and after discount. (groups based on discount then find revenue based on group. Use case) ------------------------------------------------------
SELECT 
    CASE
        WHEN discount_pct = 0 THEN 'no_discount'
        WHEN discount_pct = 5 THEN 'low'
        WHEN discount_pct = 10 THEN 'medium'
        WHEN discount_pct = 15 THEN 'high'
    END AS discount_range,
    SUM(quantity * unit_price) AS total_revenue
FROM
    orders
GROUP BY CASE
    WHEN discount_pct = 0 THEN 'no_discount'
    WHEN discount_pct = 5 THEN 'low'
    WHEN discount_pct = 10 THEN 'medium'
    WHEN discount_pct = 15 THEN 'high'
END;

-- 12. Calculate monthly: Orders, Gross revenue, Discount amount, Net revenue --------------------------------------------------------------------------------------------------
SELECT 
    MONTHNAME(order_date) AS month_name,
    COUNT(order_id) AS order_counts,
    SUM(quantity * unit_price) AS total_revenue,
    AVG(discount_pct)
FROM
    orders
GROUP BY MONTHNAME(order_date);

-- 13. Month-over-Month Revenue Growth -----------------------------------------------------------------------------------------------------------------------------------------
WITH monthly_revenue AS
( SELECT DATE_FORMAT(order_date, '%Y-%m') AS month,
		 SUM( quantity * unit_price - quantity * unit_price * discount_pct / 100 ) AS revenue
FROM orders
GROUP BY DATE_FORMAT(order_date, '%Y-%m')
),

revenue_with_previous AS
( SELECT month,
         revenue,
         LAG(revenue) OVER ( ORDER BY month) AS previous_month_revenue
FROM monthly_revenue
)
SELECT month,
       revenue,
       previous_month_revenue,
       ROUND(
        (revenue - previous_month_revenue) * 100.0 / previous_month_revenue,2) AS mom_growth_percentage
FROM revenue_with_previous;

-- 14. For every category, find the product with the highest revenue. ----------------------------------------------------------------------------------------------------------
With city_ranked_customer AS (
SELECT 
    o.product_category,
    c.customer_id,
    SUM(o.quantity * o.unit_price) AS total_revenue,
    rank () over (partition by city order by SUM(o.quantity * o.unit_price) desc) as revenue_rank
FROM
    customers c
        JOIN
    orders o ON c.customer_id = o.customer_id
    group by o.product_category,  c.customer_id
)
select * from city_ranked_customer where revenue_rank= 1;

-- 15. Which category has the worst average delivery performance? --------------------------------------------------------------------------------------------------------------
SELECT 
    product_category,
    ROUND(Avg(delivery_days),2) as avg_delivery_day
FROM
    orders
GROUP BY product_category
ORDER BY avg_delivery_day DESC;

